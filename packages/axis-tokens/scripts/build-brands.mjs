/**
 * AXIS Design System - 브랜드 CSS 빌드 (WI-0025 M2, FR-4 · FR-5, build-tokens.mjs 5단계)
 *
 * build-tokens.mjs 는 최상위 await 스크립트라 import 하면 빌드가 통째로 돈다.
 * 5단계를 함수로 떼어 두어 test/build-brands.test.mjs 가 fixture 브랜드와 임시 dist 로
 * 같은 경로(검증 · SD 필터 · css/axis-brand 포맷 · 선택자 · shadcn 결합 · brand.json 복사 ·
 * 잔여 산출물 삭제 · 임시 디렉터리 정리)를 그대로 실행할 수 있게 한다.
 */

import StyleDictionary from 'style-dictionary';
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';
import {
  listBrands,
  loadBrand,
  collectBasePaths,
  validateBrand,
  checkBrandExports,
  brandSelectors,
  renderShadcnBlock,
  renderBrandBlock,
  missingBrandDeclarations,
  brandPathKeys,
  pathKey,
  parseShadcnRootKeys,
  cssVarName,
  SHADCN_KEYS,
} from './brands.mjs';
import { registerThemePreprocessors, themePreprocessorsFor } from './theme-modes.mjs';

export const BRAND_FORMAT = 'css/axis-brand';

// --- 커스텀 포맷: 브랜드 CSS 블록 (WI-0025 B1) ---
// file.options.selector 로 선택자를, file.options.extra 로 shadcn 선언 줄을 받는다.
StyleDictionary.registerFormat({
  name: BRAND_FORMAT,
  format: async ({ dictionary, file }) => renderBrandBlock(
    file.options.selector,
    dictionary.allTokens.map(token => `  ${cssVarName(token.path)}: ${token.value};`),
    file.options?.extra,
  ),
});

// WI-0033 다크 preprocessor: component 의 $extensions.axis.dark 를 다크 빌드에서 value 로 바꾼다.
// 이게 없으면 브랜드 다크가 component 를 참조할 때 라이트 값이 나온다.
registerThemePreprocessors(StyleDictionary);

/** SD 소스 글롭은 슬래시 구분자여야 한다(Windows 경로 대비) */
function globPath(...parts) {
  return join(...parts).replace(/\\/g, '/');
}

/**
 * 테마 하나의 브랜드 블록을 만든다.
 *
 * SD 4.4.0 은 필터 결과가 0건인 파일의 output 키를 아예 빼고 돌려준다. 그대로 쓰면
 * shadcn 섹션만 있는 테마(--axis-* 0개)가 블록째 사라지고 rc 0 으로 끝난다.
 * 그래서 0건이면 같은 렌더러로 직접 만들고, 어느 경우든 브랜드에 적은 선언이 모두
 * 산출물에 있는지 대조해 빠지면 예외를 던진다.
 */
async function renderTheme({ brand, theme, srcDir, tmpRoot, selector }) {
  const tmpFile = join(tmpRoot, `${brand.name}-${theme}.json`);
  writeFileSync(tmpFile, JSON.stringify(brand[theme], null, 2));
  const paths = brandPathKeys(brand[theme]);
  const extra = renderShadcnBlock(brand.shadcn[theme]);

  // 다크도 component 를 넣어 브랜드 다크의 component 참조가 풀리게 한다 (B3 ③)
  const sd = new StyleDictionary({
    preprocessors: themePreprocessorsFor(theme),
    source: [
      globPath(srcDir, 'primitives', '**', '*.json'),
      globPath(srcDir, 'semantic', `${theme}.json`),
      globPath(srcDir, 'component', '**', '*.json'),
      globPath(tmpFile),
    ],
    log: { verbosity: 'silent' },
    platforms: {
      css: {
        transformGroup: 'css',
        files: [{
          destination: `${brand.name}-${theme}.css`,
          format: BRAND_FORMAT,
          filter: token => paths.has(pathKey(token.path)),
          options: { selector, extra },
        }],
      },
    },
  });

  let results;
  try {
    results = await sd.formatPlatform('css');
  } catch (err) {
    // SD 4.4.0 은 순환 참조도 「Some token references (N) could not be found」로만 알린다.
    // 브랜드가 component 를 역참조한 경우가 가장 흔하므로 원인 후보를 함께 적는다.
    if (err instanceof Error && /Reference Errors/.test(err.message)) {
      throw new Error(
        `[${brand.name}] ${theme}: 토큰 참조를 풀지 못했습니다. 참조 대상이 없거나, `
        + `브랜드 ${theme}.json 이 component 토큰을 참조하고 그 component 값이 다시 같은 브랜드 토큰을 `
        + `가리켜 순환이 생겼을 수 있습니다(예: surface.default = {card.bg.default}).\n${err.message}`,
        { cause: err },
      );
    }
    throw err;
  }
  let output = results[0]?.output;
  if (output === undefined) {
    if (paths.size > 0) {
      throw new Error(`[${brand.name}] ${theme}: 브랜드 토큰 ${paths.size}개가 SD 출력에서 모두 빠졌습니다`);
    }
    output = renderBrandBlock(selector, [], extra);
  }
  if (typeof output !== 'string') {
    throw new Error(`[${brand.name}] ${theme}: SD 출력이 문자열이 아닙니다`);
  }

  const missing = missingBrandDeclarations(output, {
    selector,
    tree: brand[theme],
    shadcn: brand.shadcn[theme],
  });
  if (missing.length > 0) {
    throw new Error(`[${brand.name}] ${theme}: 산출물에 빠진 선언이 있습니다: ${missing.join(', ')}`);
  }
  return output;
}

function brandHeader(name) {
  return `/**
 * AXIS Design System - Brand: ${name}
 * Generated by Style Dictionary
 * Do not edit directly
 *
 * Usage (variables.css · shadcn-compat.css 뒤에 import):
 *   @import '@axis-ds/tokens/css/brands/${name}';
 */
`;
}

/**
 * 브랜드 CSS 와 brand.json 을 dist 에 만든다. 파일을 쓰지 않고 위반만 모아 돌려주는 경로와
 * 빌드 경로를 한 함수에 두어, 테스트가 빌드 스크립트와 같은 코드를 탄다.
 *
 * @param {object} opts
 * @param {string} opts.srcDir 기본 토큰 소스 디렉터리(primitives · semantic · component)
 * @param {string} opts.brandsDir 브랜드 디렉터리(`src/brands`)
 * @param {string} opts.distDir 산출물 디렉터리(`dist`)
 * @param {object} opts.pkg package.json 객체(B5 exports 검사)
 * @param {string} opts.shadcnCss 4단계가 만든 shadcn-compat.css 본문(SHADCN_KEYS 드리프트 검사)
 * @param {string} [opts.tmpParent] 임시 디렉터리를 만들 부모(기본 os.tmpdir(), plan 3절 결정 11)
 * @returns {Promise<{ brands: string[], violations: string[], files: string[] }>}
 *   violations 가 비어 있지 않으면 아무 파일도 쓰지 않는다(잔여 산출물 삭제는 이미 끝난 상태).
 */
export async function buildBrands({ srcDir, brandsDir, distDir, pkg, shadcnCss, tmpParent = tmpdir() }) {
  const cssDir = join(distDir, 'css', 'brands');
  const metaDir = join(distDir, 'brands');

  // 이전 빌드에서 남은 브랜드 산출물을 지워 dist 가 현재 src 와 맞게 한다
  rmSync(cssDir, { recursive: true, force: true });
  rmSync(metaDir, { recursive: true, force: true });

  const brandNames = listBrands(brandsDir);
  if (brandNames.length === 0) return { brands: [], violations: [], files: [] };

  const base = collectBasePaths(srcDir);
  const brands = brandNames.map(name => loadBrand(brandsDir, name));

  const violations = brands.flatMap(brand => validateBrand(brand, base));
  violations.push(...checkBrandExports(pkg, brandNames));

  // SHADCN_KEYS 는 buildShadcnVars 이름의 복제본이라 드리프트를 여기서 막는다
  const shadcnRootKeys = parseShadcnRootKeys(shadcnCss);
  if (shadcnRootKeys.join(',') !== SHADCN_KEYS.join(',')) {
    violations.push(`SHADCN_KEYS(scripts/brands.mjs)가 shadcn-compat.css :root 이름과 다릅니다: ${shadcnRootKeys.join(',')}`);
  }

  if (violations.length > 0) return { brands: brandNames, violations, files: [] };

  const files = [];
  // 임시 파일은 dist 밖에 두고 finally 에서 지운다 (plan 3절 결정 11)
  const tmpRoot = mkdtempSync(join(tmpParent, 'axis-brands-'));
  try {
    for (const brand of brands) {
      const selectors = brandSelectors(brand.name);
      const blocks = [];
      for (const theme of ['light', 'dark']) {
        const selector = selectors[theme].join(',\n');
        const block = await renderTheme({ brand, theme, srcDir, tmpRoot, selector });
        if (block !== '') blocks.push(block);
      }

      mkdirSync(cssDir, { recursive: true });
      const cssFile = join(cssDir, `${brand.name}.css`);
      writeFileSync(cssFile, `${brandHeader(brand.name)}\n${blocks.join('\n')}`);
      files.push(cssFile);

      const metaFile = join(metaDir, brand.name, 'brand.json');
      mkdirSync(join(metaDir, brand.name), { recursive: true });
      copyFileSync(join(brandsDir, brand.name, 'brand.json'), metaFile);
      files.push(metaFile);
    }
  } finally {
    rmSync(tmpRoot, { recursive: true, force: true });
  }

  return { brands: brandNames, violations: [], files };
}
