// 1~4단계 산출물은 건드리지 않는다. 브랜드가 0개이면 아무 파일도 만들지 않는다.
import { mkdtempSync, rmSync, copyFileSync } from 'fs';
import { tmpdir } from 'os';
import { join as joinPath } from 'path';
import {
  listBrands,
  loadBrand,
  collectBasePaths,
  validateBrand,
  checkBrandExports,
  brandSelectors,
  renderShadcnBlock,
  brandPathKeys,
  pathKey,
  parseShadcnRootKeys,
  SHADCN_KEYS,
} from './scripts/brands.mjs';

// 이전 빌드에서 남은 브랜드 산출물을 지워 dist 가 현재 src 와 맞게 한다
rmSync('dist/css/brands', { recursive: true, force: true });
rmSync('dist/brands', { recursive: true, force: true });

const brandNames = listBrands('src/brands');

if (brandNames.length > 0) {
  const base = collectBasePaths('src');
  const brands = brandNames.map(name => loadBrand('src/brands', name));

  const violations = brands.flatMap(brand => validateBrand(brand, base));
  violations.push(...checkBrandExports(loadJson('package.json'), brandNames));

  // SHADCN_KEYS 는 buildShadcnVars 이름의 복제본이라 드리프트를 여기서 막는다
  const shadcnRootKeys = parseShadcnRootKeys(shadcnCss);
  if (shadcnRootKeys.join(',') !== SHADCN_KEYS.join(',')) {
    violations.push(`SHADCN_KEYS(scripts/brands.mjs)가 shadcn-compat.css :root 이름과 다릅니다: ${shadcnRootKeys.join(',')}`);
  }

  if (violations.length > 0) {
    console.error(`  ✗ 브랜드 검증 실패 (${violations.length}건)`);
    violations.forEach(v => console.error(`    - ${v}`));
    process.exit(1);
  }

  // 임시 파일은 dist 밖(os.tmpdir)에 두고 finally 에서 지운다 (plan 3절 결정 11)
  const tmpRoot = mkdtempSync(joinPath(tmpdir(), 'axis-brands-'));
  try {
    for (const brand of brands) {
      const selectors = brandSelectors(brand.name);
      const blocks = [];

      for (const theme of ['light', 'dark']) {
        const tmpFile = joinPath(tmpRoot, `${brand.name}-${theme}.json`);
        writeFileSync(tmpFile, JSON.stringify(brand[theme], null, 2));
        const paths = brandPathKeys(brand[theme]);

        // 다크도 component 를 넣어 브랜드 다크의 component 참조가 풀리게 한다 (B3 ③)
        const sd = new StyleDictionary({
          source: [
            'src/primitives/**/*.json',
            `src/semantic/${theme}.json`,
            'src/component/**/*.json',
            tmpFile,
          ],
          log: { verbosity: 'silent' },
          platforms: {
            css: {
              transformGroup: 'css',
              files: [{
                destination: `${brand.name}-${theme}.css`,
                format: 'css/axis-brand',
                filter: token => paths.has(pathKey(token.path)),
                options: {
                  selector: selectors[theme].join(',\n'),
                  extra: renderShadcnBlock(brand.shadcn[theme]),
                },
              }],
            },
          },
        });
        const [{ output }] = await sd.formatPlatform('css');
        blocks.push(output);
      }

      const brandCss = `/**
 * AXIS Design System - Brand: ${brand.name}
 * Generated by Style Dictionary
 * Do not edit directly
 *
 * Usage (variables.css · shadcn-compat.css 뒤에 import):
 *   @import '@axis-ds/tokens/css/brands/${brand.name}';
 */

${blocks.join('\n')}`;

      mkdirSync('dist/css/brands', { recursive: true });
      writeFileSync(`dist/css/brands/${brand.name}.css`, brandCss);
      mkdirSync(`dist/brands/${brand.name}`, { recursive: true });
      copyFileSync(`src/brands/${brand.name}/brand.json`, `dist/brands/${brand.name}/brand.json`);
      console.log(`  ✓ brands/${brand.name}.css generated`);
    }
  } finally {
    rmSync(tmpRoot, { recursive: true, force: true });
  }
}

console.log('Done!');
